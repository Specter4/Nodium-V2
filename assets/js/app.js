  function initReveal() {
    var reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    var io = ("IntersectionObserver" in window && !reduced)
      ? new IntersectionObserver(function (entries) {
          entries.forEach(function (entry) {
            if (entry.isIntersecting) {
              entry.target.classList.add("is-visible");
              io.unobserve(entry.target);
            }
          });
        }, { threshold: 0.1, rootMargin: "0px 0px -36px 0px" })
      : null;
    /* exposed so dynamically-injected content can be observed too.
       Call N.reveal() after ANY DOM injection to animate the new bits. */
    N.reveal = function () {
      /* stagger children of [data-reveal-group] */
      document.querySelectorAll("[data-reveal-group]").forEach(function (group) {
        Array.prototype.forEach.call(group.children, function (child, i) {
          if (child.hasAttribute("data-reveal")) {
            child.style.setProperty("--d", (i * 70) + "ms");
          }
        });
      });
      document.querySelectorAll("[data-reveal]").forEach(function (el) {
        if (el.classList.contains("is-visible")) return;
        if (io) { io.observe(el); } else { el.classList.add("is-visible"); }
      });
    };
    N.reveal();
  }

  function initCounters() {
    var reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    var io = ("IntersectionObserver" in window && !reduced)
      ? new IntersectionObserver(function (entries) {
          entries.forEach(function (entry) {
            if (entry.isIntersecting && !entry.target.dataset.counted) {
              var el = entry.target;
              el.dataset.counted = "1";
              var target = parseFloat(el.getAttribute("data-counter"));
              var decimals = parseInt(el.getAttribute("data-decimals") || "0", 10);
              var suffix = el.getAttribute("data-suffix") || "";
              var dur = 1400, t0 = null;
              function frame(t) {
                if (!t0) t0 = t;
                var p = Math.min(1, (t - t0) / dur);
                p = 1 - Math.pow(1 - p, 3); /* ease-out cubic */
                var val = target * p;
                el.textContent = val.toLocaleString("en-US", { minimumFractionDigits: decimals, maximumFractionDigits: decimals }) + suffix;
                if (p < 1) requestAnimationFrame(frame);
              }
              requestAnimationFrame(frame);
              io.unobserve(el);
            }
          });
        }, { threshold: 0.4 })
      : null;
    /* exposed so dynamically-injected counters animate too */
    N.counters = function () {
      document.querySelectorAll("[data-counter]").forEach(function (el) {
        if (el.dataset.counted) return;
        if (io) { io.observe(el); } else {
          el.dataset.counted = "1";
          el.textContent = parseFloat(el.getAttribute("data-counter")).toLocaleString("en-US") + (el.getAttribute("data-suffix") || "");
        }
      });
    };
    N.counters();
  }

  /* ==================================================================
     ACCORDION (shared behaviour for FAQ / product details / mobile nav)
     ================================================================== */
  function initAccordions() {
    document.addEventListener("click", function (e) {
      var q = e.target.closest(".acc-q");
      if (!q) return;
      var item = q.parentElement;
      var panel = item.querySelector(".accordion-panel");
      var open = q.getAttribute("aria-expanded") === "true";
      /* optional single-open behaviour */
      var list = item.parentElement;
      if (list && list.classList.contains("acc-single")) {
        list.querySelectorAll(".acc-item").forEach(function (other) {
          if (other !== item) {
            other.querySelector(".acc-q").setAttribute("aria-expanded", "false");
            other.querySelector(".accordion-panel").classList.remove("open");
          }
        });
      }
      q.setAttribute("aria-expanded", String(!open));
      if (panel) panel.classList.toggle("open", !open);
    });
  }

  /* ==================================================================
     TOAST
     ================================================================== */
  function showToast(msg, linkText, linkHref) {
    var toast = document.getElementById("toast");
    if (!toast) return;
    toast.innerHTML =
      '<span class="t-msg">' + msg + "</span>" +
      (linkText && linkHref ? '<a class="t-link" href="' + linkHref + '">' + linkText + "</a>" : "");
    toast.hidden = false;
    requestAnimationFrame(function () { toast.classList.add("show"); });
    clearTimeout(toast._t);
    toast._t = setTimeout(function () {
      toast.classList.remove("show");
      setTimeout(function () { toast.hidden = true; }, 500);
    }, 3200);
  }
  window.N.showToast = showToast;

