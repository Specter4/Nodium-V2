  /* --- header behaviour: scroll state, mega menu, mobile nav --- */
  function initHeader() {
    var header = document.getElementById("site-header");
    var navProducts = document.getElementById("nav-products");
    var mega = document.getElementById("mega-panel");
    var hamburger = document.getElementById("hamburger");
    var mobileNav = document.getElementById("mobile-nav");
    var mnavBtn = document.getElementById("mnav-products-btn");

    function onScroll() {
      header.classList.toggle("scrolled", window.scrollY > 16);
    }
    window.addEventListener("scroll", onScroll, { passive: true });
    onScroll();

    /* mega menu: hover / click / focus */
    function openMega() {
      navProducts.classList.add("open");
      mega.classList.add("open");
      navProducts.querySelector("button").setAttribute("aria-expanded", "true");
    }
    function closeMega() {
      navProducts.classList.remove("open");
      mega.classList.remove("open");
      navProducts.querySelector("button").setAttribute("aria-expanded", "false");
    }
    navProducts.addEventListener("mouseenter", openMega);
    mega.addEventListener("mouseenter", openMega);
    header.addEventListener("mouseleave", function (e) {
      if (e.relatedTarget && !header.contains(e.relatedTarget)) closeMega();
    });
    mega.addEventListener("mouseleave", closeMega);
    navProducts.querySelector("button").addEventListener("click", function () {
      mega.classList.contains("open") ? closeMega() : openMega();
    });
    document.addEventListener("focusin", function (e) {
      if (mega.classList.contains("open") && !header.contains(e.target)) closeMega();
    });

    /* mobile nav */
    function openMnav() {
      mobileNav.classList.add("open");
      hamburger.setAttribute("aria-expanded", "true");
      hamburger.setAttribute("aria-label", "Close menu");
      document.body.classList.add("no-scroll");
    }
    function closeMnav() {
      mobileNav.classList.remove("open");
      hamburger.setAttribute("aria-expanded", "false");
      hamburger.setAttribute("aria-label", "Open menu");
      document.body.classList.remove("no-scroll");
    }
    hamburger.addEventListener("click", function () {
      mobileNav.classList.contains("open") ? closeMnav() : openMnav();
    });
    mobileNav.querySelector("[data-close-mnav]").addEventListener("click", closeMnav);
    mobileNav.querySelectorAll("a").forEach(function (a) {
      a.addEventListener("click", closeMnav);
    });
    mnavBtn.addEventListener("click", function () {
      var open = mnavBtn.getAttribute("aria-expanded") === "true";
      mnavBtn.setAttribute("aria-expanded", String(!open));
      document.getElementById("mnav-cats").classList.toggle("open", !open);
    });

    /* Esc closes everything */
    document.addEventListener("keydown", function (e) {
      if (e.key !== "Escape") return;
      closeMega();
      if (mobileNav.classList.contains("open")) closeMnav();
      var drawer = document.getElementById("cart-drawer");
      if (drawer && drawer.classList.contains("open")) drawer.dispatchEvent(new CustomEvent("close-cart"));
    });
  }

